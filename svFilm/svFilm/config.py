def key_signature(mod=None):
    """把「会影响出图的 config 值」压成一个**可哈希、可比较**的指纹。

    用途：① `pipeline` 的段缓存键；② `presets._params_for` 的缓存键；
    ③ `service` 的解码签名（替代那个已经恒为空的 `_DECODE_SIG_KEYS`）。

    ⚠ 只收「值可哈希」的；不可哈希的退化成 `repr`（宁可保守地作废缓存，也别静默漏项）。
    """
    import sys as _sys
    m = mod if mod is not None else _sys.modules[__name__]
    out = []
    for k in dir(m):
        if k.startswith('_'):
            continue
        if k in CACHE_KEY_EXTRA or k.startswith(CACHE_KEY_PREFIXES):
            v = getattr(m, k)
            try:
                hash(v)
                out.append((k, v))
            except TypeError:
                out.append((k, repr(v)))
    return tuple(sorted(out))

