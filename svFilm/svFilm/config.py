ENTRY_KNEE = 0.80               # 软肩部起点（显示域线性亮度）
ENTRY_CEIL = 0.985              # 肩部顶端（不硬裁，留一档余量给 L4）
# ★★ 肩的**形状族**（09-14 晚）：实测「指数肩」把 raw L*70 以上全挤进 96~99.4
#   —— 高光的层次在**入口**就丢了（占高光压缩总量的 98.6%），后面每层都救不回来。
#   `exp` = 老行为 `knee + d·(1−e^−u/d)`：u=(y−knee)/d，斜率 ∝ e^−u ⇒ u=5 时只剩 0.7%，
#           几乎全平 ⇒ 上面全是同一块白。
#   `log` = `knee + d·ln(1+u)/ln(1+UMAX)`：斜率 ∝ 1/((1+u)·ln(1+UMAX)) ⇒ u=5 时还有 5.5%，
#           **高光段被展得更开**（合成灰阶上：raw70→100 的铺开度 3.31 → 5.06 L*）。仍严格有界于 CEIL。
#   ⚠⚠ **实测结论（09-14 晚）：换成 log 在真图上几乎没用** —— 四张片的 L90 逐位不变，
