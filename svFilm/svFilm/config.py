#   ⇒ `(Y·2^ev)^ENTRY_GAMMA · a` 在 Y→0 时增益**无上限**。实测（0791，DR400）：
#     **相机交给我们的线性暗部比作者线A还黑**（P5 = L\*3.0），入口却按 ×12.18 放大抬到 **L\*21.8**；
