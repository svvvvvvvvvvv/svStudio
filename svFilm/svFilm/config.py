# 段缓存键必须覆盖「任何改了就会换出图的东西」；手抄元组必然漏 ⇒ 由「**前缀表 + 显式补遗**」
# 生成（`key_signature()`），它同时当 `presets._params_for` 的缓存键。
# ⚠ **新增旋钮必须补前缀**，否则就是"改了没反应"。
# ★★ `PERSON_` / `FACE_` 是 10-17 补的：`PERSON_PE_*` 定印相曝光落点、`FACE_*` 定"脸算不算数"
#    ⇒ 两者都会改出图，却**一个都不在原前缀里**（缓存键看不出变化 ⇒ 改了还是老图）。
CACHE_KEY_PREFIXES = ('SPEK_', 'PRESET_', 'PUBLIC_', 'SCANFIX_', 'CHROMA_', 'GRAIN_',
                      'LENS_', 'HALATION_', 'EXPOSURE_', 'PERSON_', 'FACE_')
CACHE_KEY_EXTRA = ('MAX_SIDE', 'STOCK')


def key_signature(mod=None):
    """把「会影响出图的 config 值」压成一个**可哈希、可比较**的指纹（用途：段缓存键 /
    `presets._params_for` 的缓存键 / 解码签名）。⚠ 不可哈希的退化成 `repr`（宁可靠保守作废缓存）。"""
    import sys as _sys
    m = mod if mod is not None else _sys.modules[__name__]
    out = []
    for k in dir(m):
        if k.startswith('_'):
            continue
        if k in CACHE_KEY_EXTRA or k.startswith(CACHE_KEY_PREFIXES):
            v = getattr(m, k)
            try:
                hash(v)
                out.append((k, v))
            except TypeError:
                out.append((k, repr(v)))
    return tuple(sorted(out))

