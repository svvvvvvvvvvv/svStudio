#   **LO/HI 不是绝对亮度，而是「入口自己吐出来的亮度 y 的中位」的固定倍数**
#   —— 也就是**内容归一**。⚠ 这一条是**实测逼出来的**，别改回绝对值：
#     固定绝对断点（y 0.02~0.20）在**亮场**上正好（0791/0805/2328 就是按它定的档），
#     但在**暗片**上整张图都落在 y<0.20 ⇒ 趾部退化成"全图乘 0.32"：
#     A/B 实测 DSCF0071 成片中灰 28.8 → 16.5、DSCF0188 15.6 → 5.8（不是"只动最底部"）。
#   项目既有原则本来就是「形状抄大师**内容归一后**的形状，不能抄绝对亮度」（见 MEMORY 的「三把尺子」）。
#   相对锚点下的等效倍数（把绝对 0.02/0.20 折算成"中位的几倍"）：
