#   按作者线A靶反解"本该放大多少"：底部 **×2.5**、中灰 ×8.2、亮部 ×3.9 ⇒ **只有最底部过头 5 倍**。
#   ⇒ 这是**形状**问题（胶片 H&D 曲线本来就"趾部 + 直线 + 肩部"三段），
#     **不是位置问题** ⇒ 不违反"位置听相机"（中灰落点那一段**逐位不动**）。
