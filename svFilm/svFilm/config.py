#   ② 形状：`y' = ENTRY_LEVEL · y^ENTRY_GAMMA` + **软肩部**（ENTRY_KNEE 之上平滑压向 ENTRY_CEIL）
# 依据：ENTRY_GAMMA 让"纯底形状"穿过大师带（纯底 q90 +2.03 → ×0.886 = +1.80，大师中位 +1.83）；
